"""Tests for the prototype pipeline: toy SCM data, test-time perturbations and SHAP."""

from pathlib import Path

import numpy as np
import pandas as pd
import pytest
import shap
from sklearn.linear_model import LogisticRegression

from causal_foundations import (
    causal_precision_at_k,
    compute_shap_values,
    load_prototype_environments,
    logistic_scm_probability,
    perturb_feature,
    prototype_counterfactual,
    shap_importance,
)
from causal_foundations.data import PROTOTYPE_FEATURES

PROTOTYPE_ZIP = Path(__file__).resolve().parents[1] / "data" / "prototype" / "dados_scm.zip"


def _toy_scm(n: int = 400, seed: int = 0) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    X1, X2, Z = rng.normal(size=(3, n))
    Y = (1.5 * X1 - 1.0 * X2 + rng.logistic(size=n) > 0).astype(int)
    S = 2.0 * (2 * Y - 1) + rng.normal(size=n)
    return pd.DataFrame({"X1": X1, "X2": X2, "S": S, "Z": Z, "Y": Y})


def test_load_prototype_environments() -> None:
    """Training set and the 6 environments x 5 seeds generated by the SCM notebook."""
    train, envs = load_prototype_environments(PROTOTYPE_ZIP)
    assert set(PROTOTYPE_FEATURES + ["Y"]).issubset(train.columns)
    assert len(train) == 2000
    assert envs["ambiente"].nunique() == 6
    assert envs.groupby("ambiente")["seed"].nunique().eq(5).all()
    assert sorted(envs["alpha"].unique()) == [-2.0, -1.0, 0.0, 0.5, 1.0, 2.0]


def test_perturb_feature_only_touches_target_column() -> None:
    df = _toy_scm()
    X = df[PROTOTYPE_FEATURES]

    negated = perturb_feature(X, "S", "negate")
    np.testing.assert_allclose(negated["S"], -X["S"])
    pd.testing.assert_frame_equal(negated.drop(columns="S"), X.drop(columns="S"))
    assert np.corrcoef(negated["S"], df.Y)[0, 1] < -0.8

    np.testing.assert_allclose(perturb_feature(X, "S", "scale", 0.5)["S"], 0.5 * X["S"])
    np.testing.assert_allclose(perturb_feature(X, "S", "shift", 2.0)["S"], X["S"] + 2.0)
    assert (perturb_feature(X, "S", "constant", 0.0)["S"] == 0.0).all()

    permuted = perturb_feature(X, "S", "permute")
    np.testing.assert_allclose(np.sort(permuted["S"]), np.sort(X["S"]))
    assert abs(np.corrcoef(permuted["S"], df.Y)[0, 1]) < 0.2

    # X itself is never modified
    pd.testing.assert_frame_equal(X, df[PROTOTYPE_FEATURES])

    with pytest.raises(ValueError):
        perturb_feature(X, "S", "unknown")


def test_compute_shap_values_matches_shap_exact_explainer() -> None:
    """Vectorized exact SHAP equals shap.ExactExplainer with an Independent masker."""
    df = _toy_scm()
    X = df[PROTOTYPE_FEATURES]
    model = LogisticRegression().fit(X, df.Y)
    X_explain, background = X.iloc[:20], X.iloc[200:230]

    ours = compute_shap_values(model, X_explain, background, n_background=len(background))

    def f(data: np.ndarray) -> np.ndarray:
        return model.predict_proba(pd.DataFrame(data, columns=X.columns))[:, 1]

    masker = shap.maskers.Independent(background, max_samples=len(background))
    reference = shap.ExactExplainer(f, masker)(X_explain)

    np.testing.assert_allclose(ours.values, reference.values, atol=1e-8)
    np.testing.assert_allclose(ours.base_values, reference.base_values, atol=1e-8)

    # Efficiency: SHAP values add up to the prediction minus the base value
    np.testing.assert_allclose(
        ours.values.sum(axis=1) + ours.base_values, f(X_explain.to_numpy()), atol=1e-8
    )


def test_shap_importance_and_causal_precision() -> None:
    df = _toy_scm()
    X = df[PROTOTYPE_FEATURES]
    model = LogisticRegression().fit(X, df.Y)
    importance = shap_importance(compute_shap_values(model, X.iloc[:50], X))

    assert list(importance.index[:1]) == ["S"]  # with alpha = 2 the shortcut dominates
    assert importance["Z"] == importance.min()

    assert causal_precision_at_k(pd.Series({"X1": 3, "X2": 2, "S": 1, "Z": 0}), ["X1", "X2"]) == 1.0
    assert causal_precision_at_k(pd.Series({"S": 3, "X1": 2, "X2": 1, "Z": 0}), ["X1", "X2"]) == 0.5


def test_logistic_scm_probability_ignores_non_parents() -> None:
    df = _toy_scm()
    p = logistic_scm_probability(df)
    np.testing.assert_allclose(p, 1 / (1 + np.exp(-(1.5 * df.X1 - 1.0 * df.X2))))
    pd.testing.assert_series_equal(p, logistic_scm_probability(df.assign(S=0.0, Z=0.0)))
    # empirical frequency of Y follows the true probability
    assert abs(df.Y.mean() - p.mean()) < 0.05


def test_prototype_counterfactual() -> None:
    df = _toy_scm(n=5000)

    # No intervention: the counterfactual world is the factual one (consistency)
    same = prototype_counterfactual(df, alpha=2.0, interventions={})
    pd.testing.assert_frame_equal(same, df, check_dtype=False)

    # Extreme intervention on a cause: Y flips to 1 and S follows Y with the same noise
    cf = prototype_counterfactual(df, alpha=2.0, interventions={"X1": 10.0})
    assert (cf.Y == 1).all()
    np.testing.assert_allclose(cf.S - 2.0 * (2 * cf.Y - 1), df.S - 2.0 * (2 * df.Y - 1))
    pd.testing.assert_series_equal(cf.X2, df.X2)

    # Intervening on noise Z changes nothing downstream
    cf_z = prototype_counterfactual(df, alpha=2.0, interventions={"Z": 3.0})
    pd.testing.assert_series_equal(cf_z.Y, df.Y)

    # Average over rows matches the interventional probability E[sigmoid(1.5 x - X2)]
    cf_0 = prototype_counterfactual(df, alpha=2.0, interventions={"X1": 0.5})
    expected = logistic_scm_probability(df.assign(X1=0.5)).mean()
    assert abs(cf_0.Y.mean() - expected) < 0.03

    with pytest.raises(ValueError):
        prototype_counterfactual(df, alpha=2.0, interventions={"S": 0.0})
